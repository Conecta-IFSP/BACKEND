import 'reflect-metadata';
import assert from 'node:assert/strict';
import { randomUUID, createHash } from 'node:crypto';
import mongoose from 'mongoose';
import nodemailer from 'nodemailer';
import { Test } from '@nestjs/testing';
import { ValidationPipe } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { JwtService } from '@nestjs/jwt';
import { getModelToken } from '@nestjs/mongoose';
import request from 'supertest';
import { UsuarioSchema } from '../dist/usuarios/schemas/usuario.schema.js';
import { ComissaoSchema } from '../dist/comissoes/schemas/comissao.schema.js';
import { OrganizacaoSchema } from '../dist/organizacoes/schemas/organizacao.schema.js';
import { ReuniaoSchema } from '../dist/reunioes/schemas/reuniao.schema.js';
import { NotificacaoSchema } from '../dist/notificacoes/notificacao.schema.js';
import { NotificacoesService } from '../dist/notificacoes/notificacoes.service.js';
import { NotificacoesController } from '../dist/notificacoes/notificacoes.controller.js';
import { PresencasService } from '../dist/presencas/presencas.service.js';
import { PresencasController } from '../dist/presencas/presencas.controller.js';
import { JwtAuthGuard } from '../dist/auth/jwt-auth.guard.js';
import { UsuarioComumGuard } from '../dist/auth/admin-sistema.guard.js';
import { ApiKeyGuard } from '../dist/auth/api-key.guard.js';

const banco = `conecta_teste_presenca_${randomUUID().replaceAll('-', '')}`;
await mongoose.connect(`mongodb://127.0.0.1:27019/${banco}`, { serverSelectionTimeoutMS: 5000 });
let app;
const transportOriginal = nodemailer.createTransport;
try {
  const U = mongoose.model('Usuario', UsuarioSchema), O = mongoose.model('Organizacao', OrganizacaoSchema);
  const C = mongoose.model('Comissao', ComissaoSchema), R = mongoose.model('Reuniao', ReuniaoSchema), N = mongoose.model('Notificacao', NotificacaoSchema);
  await N.init();
  const [ana, bruno, fora, admin] = await U.create(['Ana', 'Bruno', 'Fora', 'Admin'].map(nome => ({ nome, email: `${nome}@teste.local`, tipo: nome === 'Admin' ? 'ADMIN_SISTEMA' : 'USUARIO' })));
  const org = await O.create({ nome: 'Teste', cidade: 'Barretos', criada_por: ana._id, status: 'APROVADA', membros: [ana, bruno, fora].map(p => ({ usuario_id: p._id, papel: 'MEMBRO', status: 'APROVADO' })) });
  const com = await C.create({ nome: 'Comissão', organizacao_id: org._id, membros: [ana, bruno, fora].map(p => ({ usuario_id: p._id, papel: p.id === ana.id ? 'RESPONSAVEL' : 'MEMBRO' })) });
  const agora = Date.now();
  const r = await R.create({ comissao_id: com._id, criada_por: ana._id, titulo: 'Reunião de teste', inicio: new Date(agora - 3600000), fim: new Date(agora + 3600000), participantes: [ana, bruno].map(p => ({ usuario_id: p._id, convite: 'ACEITO' })) });
  const config = new ConfigService({ FRONTEND_URL: 'http://localhost:8083', API_ACCESS_TOKEN: 'teste-local' });
  const ns = new NotificacoesService(N, R), ps = new PresencasService(R, C, O, U, ns, config);
  const jwt = new JwtService({ secret: randomUUID() });
  const modulo = await Test.createTestingModule({ controllers: [PresencasController, NotificacoesController], providers: [
    { provide: PresencasService, useValue: ps }, { provide: NotificacoesService, useValue: ns },
    JwtAuthGuard, UsuarioComumGuard, { provide: JwtService, useValue: jwt }, { provide: getModelToken('Usuario'), useValue: U },
  ] }).compile();
  app = modulo.createNestApplication();
  app.useGlobalGuards(new ApiKeyGuard(config));
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true }));
  await app.init();
  const http = request(app.getHttpServer());
  const tokens = new Map(await Promise.all([ana, bruno, fora, admin].map(async p => [p.id, await jwt.signAsync({ sub: p.id })])));
  const chamar = (method, path, pessoa = ana) => http[method](path).set('X-API-Key', 'teste-local').auth(tokens.get(pessoa.id), { type: 'bearer' });
  const rota = `/presencas/${r.id}`;
  await http.post(`${rota}/link`).expect(401);
  await chamar('post', `${rota}/link`, bruno).expect(403);
  await chamar('post', `${rota}/link`, admin).expect(403);
  const link = (await chamar('post', `${rota}/link`).expect(201)).body;
  assert.equal(link.codigo.length, 64);
  const guardado = await R.findById(r.id).select('+acesso_presenca');
  assert.equal(guardado.acesso_presenca.hash, createHash('sha256').update(link.codigo).digest('hex'));
  assert.ok(!JSON.stringify(await R.findById(r.id).lean()).includes(link.codigo));
  assert.equal((await R.findById(r.id).lean()).acesso_presenca, undefined);
  await chamar('get', `${rota}/acesso?codigo=${link.codigo}`, fora).expect(403);
  await chamar('get', `${rota}/acesso?codigo=${link.codigo}`, bruno).expect(200);
  assert.equal((await R.findById(r.id)).participantes[1].presenca, undefined);
  await chamar('post', `${rota}/enviar`).send({ canal: 'APP', codigo: link.codigo }).expect(201);
  await chamar('post', `${rota}/enviar`).send({ canal: 'APP', codigo: link.codigo }).expect(201);
  const lista = (await chamar('get', '/notificacoes', bruno).expect(200)).body;
  assert.equal(lista.itens.filter(n => n.tipo === 'PRESENCA').length, 1);
  const notificacao = lista.itens.find(n => n.tipo === 'PRESENCA');
  assert.ok(notificacao.destino.includes(link.codigo));
  await chamar('patch', `/notificacoes/${notificacao._id}/lida`, fora).expect(404);
  await chamar('patch', `/notificacoes/${notificacao._id}/lida`, bruno).expect(200);
  assert.equal((await chamar('get', '/notificacoes', bruno)).body.nao_lidas, 0);
  await chamar('post', `${rota}/enviar`).send({ canal: 'EMAIL', codigo: link.codigo }).expect(503);
  const emails = [];
  config.set('MAIL_HOST', 'smtp.test'); config.set('MAIL_USER', 'conta'); config.set('MAIL_PASS', 'teste');
  nodemailer.createTransport = () => ({ sendMail: async mail => { emails.push(mail); } });
  await chamar('post', `${rota}/enviar`).send({ canal: 'EMAIL', codigo: link.codigo }).expect(201);
  assert.equal(emails.length, 1); assert.equal(emails[0].to, bruno.email); assert.ok(emails[0].text.includes(link.url));
  await R.updateOne({ _id: r._id }, { $set: { 'participantes.1.convite': 'RECUSADO' } });
  await chamar('post', `${rota}/acesso`, bruno).send({ codigo: link.codigo, acao: 'ENTRADA' }).expect(400);
  await R.updateOne({ _id: r._id }, { $set: { 'participantes.1.convite': 'ACEITO' } });
  const entradas = await Promise.all([1, 2].map(() => chamar('post', `${rota}/acesso`, bruno).send({ codigo: link.codigo, acao: 'ENTRADA' })));
  assert.deepEqual(entradas.map(e => e.status).sort(), [201, 409]);
  const entrou = (await R.findById(r.id)).participantes[1].presenca;
  assert.equal(entrou.situacao, 'CONFIRMADA'); assert.equal(entrou.marcada_por, 'LINK');
  await chamar('post', `${rota}/acesso`, bruno).send({ codigo: link.codigo, acao: 'SAIDA' }).expect(201);
  await chamar('post', `${rota}/acesso`, bruno).send({ codigo: link.codigo, acao: 'SAIDA' }).expect(409);
  const revisao = (await chamar('get', `${rota}/gestao`)).body.revisao;
  const correcao = { entrada: new Date(agora - 1800000).toISOString(), saida: new Date(agora - 600000).toISOString(), motivo: 'Horário conferido com o participante', revisao };
  await chamar('patch', `${rota}/horarios/${bruno.id}`, bruno).send(correcao).expect(403);
  await chamar('patch', `${rota}/horarios/${bruno.id}`).send({ ...correcao, motivo: '     ' }).expect(400);
  await chamar('patch', `${rota}/horarios/${bruno.id}`).send({ ...correcao, saida: new Date(agora - 7200000).toISOString() }).expect(400);
  await chamar('patch', `${rota}/horarios/${bruno.id}`).send(correcao).expect(200);
  await chamar('patch', `${rota}/horarios/${bruno.id}`).send(correcao).expect(409);
  const historico = (await chamar('get', `${rota}/historico`)).body;
  assert.equal(historico.length, 1); assert.equal(historico[0].responsavel_id, ana.id);
  assert.equal(historico[0].antes.entrada, entrou.entrada.toISOString());
  assert.equal(historico[0].depois.entrada, correcao.entrada);
  await chamar('get', `${rota}/historico`, bruno).expect(403);
  const novo = (await chamar('post', `${rota}/link`).expect(201)).body;
  await chamar('get', `${rota}/acesso?codigo=${link.codigo}`, bruno).expect(400);
  assert.equal((await chamar('get', '/notificacoes', bruno)).body.itens.filter(n => n.tipo === 'PRESENCA').length, 0);
  await chamar('delete', `${rota}/link`).expect(200);
  await chamar('get', `${rota}/acesso?codigo=${novo.codigo}`, bruno).expect(400);
  const futuro = await R.create({ comissao_id: com._id, criada_por: ana._id, titulo: 'Convite futuro', inicio: new Date(agora + 86400000), fim: new Date(agora + 90000000), participantes: [{ usuario_id: bruno._id, convite: 'PENDENTE' }, { usuario_id: ana._id, convite: 'ACEITO' }] });
  const linkFuturo = (await chamar('post', `/presencas/${futuro.id}/link`)).body;
  await chamar('post', `/presencas/${futuro.id}/acesso`, bruno).send({ codigo: linkFuturo.codigo, acao: 'ENTRADA' }).expect(400);
  const convites = (await chamar('get', '/notificacoes', bruno)).body.itens;
  assert.ok(convites.some(n => n.tipo === 'CONVITE'));
  await R.updateOne({ _id: futuro._id }, { $set: { horario_alterado_em: new Date(), fim: new Date(agora + 92000000) } });
  await chamar('get', `/presencas/${futuro.id}/acesso?codigo=${linkFuturo.codigo}`, bruno).expect(400);
  assert.ok((await chamar('get', '/notificacoes', bruno)).body.itens.some(n => n.tipo === 'HORARIO'));
  await R.updateOne({ _id: futuro._id }, { $set: { situacao: 'CANCELADA' } });
  assert.ok((await chamar('get', '/notificacoes', bruno)).body.itens.some(n => n.tipo === 'CANCELAMENTO'));
  await R.updateOne({ _id: r._id }, { $set: { ata: { conteudo: 'Ata válida com decisões de teste.', versao: 1, situacao: 'EM_APROVACAO', autor_id: ana._id, atualizada_em: new Date(), aprovadores: [bruno._id], avaliacoes: [] } } });
  assert.ok((await chamar('get', '/notificacoes', bruno)).body.itens.some(n => n.tipo === 'ATA'));
  await chamar('patch', `${rota}/horarios/${bruno.id}`).send({ ...correcao, revisao: revisao + 1 }).expect(400);
  await U.updateOne({ _id: bruno._id }, { $set: { ativo: false } });
  await chamar('get', '/notificacoes', bruno).expect(401);
  console.log('PASSOU: link restrito, GET sem presença, concorrência, expiração/revogação, e-mail simulado, notificações privadas e correções auditadas.');
} finally {
  nodemailer.createTransport = transportOriginal;
  await app?.close();
  if (mongoose.connection.name === banco && banco.startsWith('conecta_teste_presenca_')) await mongoose.connection.dropDatabase();
  await mongoose.disconnect();
}
